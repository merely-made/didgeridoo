local match = string.match

local function check(s, p, init, ...)
  local r = table.pack(match(s, p, init))
  local want = table.pack(...)
  assert(r.n == want.n, "result count for " .. tostring(p) .. ": " .. r.n)
  for i = 1, want.n do
    assert(r[i] == want[i], "result " .. i .. " for " .. tostring(p) .. ": " .. tostring(r[i]))
  end
end

-- whole match when there are no captures
check("hello 123", "%d+", nil, "123")
check("hello", "xyz", nil, nil)
check("hello", "", nil, "")
check("", "", nil, "")
check("abc", "a*", nil, "a")
check("aaa", "a-", nil, "")
check("aaa", "a-$", nil, "aaa")
check("hello", "h.l", nil, "hel")

-- captures
check("key=value", "(%w+)=(%w+)", nil, "key", "value")
check("hello", "(h)(e)(l)", nil, "h", "e", "l")
check("2024-01-15", "(%d+)-(%d+)-(%d+)", nil, "2024", "01", "15")
check("  trim  ", "^%s*(.-)%s*$", nil, "trim")
check("abc", "((a)(b))c", nil, "ab", "a", "b")
check("abc", "(a(b)(c))", nil, "abc", "b", "c")
check("abc", "()", nil, 1)
check("hello", "()ll()", nil, 3, 5)
check("abc", "(x*)", nil, "")
check("abc", "(a)(x*)", nil, "a", "")
check("abc", "a(.)c", nil, "b")
check("abc", "(b)", 3, nil)

-- init
check("hello", "(l)", 4, "l")
check("hello", ".", -1, "o")
check("hello", ".", -3, "l")
check("hello", ".", 0, "h")
check("abc", ".", 10, nil)
check("abc", "", 4, "")
check("abc", "", 5, nil)
check("hello", "h", 2, nil)

-- anchors
check("hello", "^(h)", nil, "h")
check("hello", "^(e)", nil, nil)
check("hello", "(o)$", nil, "o")
check("hello", "(l)$", nil, nil)
check("a^b", "a^b", nil, "a^b")
check("a$b", "a$b", nil, "a$b")
check("hello", "^", 2, "")
check("abc", "^b", 2, "b")

-- classes
check("abc123", "%a+", nil, "abc")
check("abc123", "%d+", nil, "123")
check("Hello World", "%u%l+", nil, "Hello")
check("  x", "%s*", nil, "  ")
check("a1!", "%p", nil, "!")
check("\1\2a", "%c+", nil, "\1\2")
check("ab c", "%g+", nil, "ab")
check("ff09zz", "%x+", nil, "ff09")
check("a_b9", "%w+", nil, "a")
check("ab12", "%D+", nil, "ab")
check("ab12", "%A+", nil, "12")
check("a b", "%S+", nil, "a")
check("abc DEF", "%L+", nil, " DEF")
check("ABc", "%U+", nil, "c")
check("a_b", "%W", nil, "_")
check("  a", "%G+", nil, "  ")
check("ab12", "%C+", nil, "ab12")
check("ab12", "%P+", nil, "ab12")
check("a.b", "%X", nil, ".")
check("h\233llo", "%a+", nil, "h")
check("a.b", "%.", nil, ".")
check("a%b", "%%", nil, "%")
check("a-b", "%-", nil, "-")
check("g", "%x", nil, nil)
check("%", "%%", nil, "%")
-- an escaped non-alphanumeric is just that character
check("a?", "%?", nil, "?")
check("[", "%[", nil, "[")

-- sets
check("hello", "[aeiou]+", nil, "e")
check("x123y", "[0-9]+", nil, "123")
check("abc", "[^a]+", nil, "bc")
check("a-b", "[a%-]+", nil, "a-")
check("a]b", "[]]", nil, "]")
check("a^b", "[%^]", nil, "^")
check("a", "[^^]", nil, "a")
check("^", "[^^]", nil, nil)
check("f-o", "[a-f%-]+", nil, "f-")
check("-", "[a-]", nil, "-")
check("b", "[a-c]", nil, "b")
check("d", "[a-c]", nil, nil)
check("%", "[%%]", nil, "%")
check("a1", "[%d]", nil, "1")
check("a1_", "[%a%d]+", nil, "a1")
check("  foo_1 bar", "[%a_][%w_]*", nil, "foo_1")
check("Z", "[a-zA-Z]", nil, "Z")
check("-5", "^[+-]?%d+$", nil, "-5")
check("+5", "^[+-]?%d+$", nil, "+5")
check("5", "^[+-]?%d+$", nil, "5")
check("a5", "^[+-]?%d+$", nil, nil)
check("\200\201", "[\128-\255]+", nil, "\200\201")
check("x", "[%a-z]", nil, "x")
check("-", "[%a-z]", nil, "-")

-- quantifiers
check("color colour", "colou?r", nil, "color")
check("colour", "colou?r", nil, "colour")
check("<a><b>", "<.->", nil, "<a>")
check("<a><b>", "<.*>", nil, "<a><b>")
check("aaa", "a+", nil, "aaa")
check("b", "a*b", nil, "b")
check("b", "a+b", nil, nil)
check("aaab", "a*ab", nil, "aaab")
check("aaa", "a-a", nil, "a")
check("abbbc", "ab-c", nil, "abbbc")
check("abbbc", "ab*c", nil, "abbbc")
check("ac", "ab*c", nil, "ac")
check("ac", "ab+c", nil, nil)
check("hello world", ".-o", nil, "hello")
check("hello world", ".*o", nil, "hello wo")
check("a.b.c", "[^.]+", nil, "a")
check("a.b.c", "^(.-)%.", nil, "a")
check("a.b.c", "^(.*)%.", nil, "a.b")
check("aXb", "a.?b", nil, "aXb")
check("ab", "a.?b", nil, "ab")

-- back-references
check("abcabc", "(abc)%1", nil, "abc")
check("xyzxyz", "(.)(.)(.)%1%2%3", nil, "x", "y", "z")
check("hello hello", "(%w+) %1", nil, "hello")
check("hello world", "(%w+) %1", nil, nil)
check("abab", "(a)(b)%1%2", nil, "a", "b")
check("aa", "(a*)%1", nil, "a")
check("xx", "(x)%1", nil, "x")
check("\"a\" 'b'", "([\"'])(.-)%1", nil, "\"", "a")
check("abc", "()%1", nil, nil)

-- balanced
check("f(a(b)c)d", "%b()", nil, "(a(b)c)")
check("[[x]]", "%b[]", nil, "[[x]]")
check("x(", "%b()", nil, nil)
check("(a", "%b()", nil, nil)
check("if (a and (b or c)) then", "%b()", nil, "(a and (b or c))")
check("'a'b'", "%b''", nil, "'a'")
check("()", "%b()", nil, "()")
check("a(b)c(d)", "%b()", 5, "(d)")
check("{{}", "%b{}", nil, "{}")
check("x(y)z", "x(%b())z", nil, "(y)")

-- frontier
check("THE (quick) fox", "%f[%a]%a+", nil, "THE")
check("THE END", "%f[%a]%a+%f[%A]", nil, "THE")
check("abc", "%f[%a]", nil, "")
check("hello world", "%f[%w]%w+$", nil, "world")
check("x hello", "%f[%a]h", nil, "h")
check("xhello", "%f[%a]h", nil, nil)
check("ab", "%f[%z]", nil, nil)
check("a.b", "%f[^%a]", nil, "")
check("a1", "%f[%d]%d", nil, "1")
check("a1", "a%f[%d]", nil, "a")

-- up to 32 captures
local thirty_two = string.rep("(.)", 32)
local subject = string.rep("x", 32)
assert(select("#", match(subject, thirty_two)) == 32)
assert(not pcall(match, subject .. "x", string.rep("(.)", 33)))

-- every position capture counts as a capture
assert(select("#", match("abc", "()()()")) == 3)

-- coercion and method form
check(12345, "3(%d)", nil, "4")
assert(("abc"):match("b") == "b")
assert(("2 + 3"):match("(%d+)%s*%+%s*(%d+)") == "2")
assert(("hello"):match("^(h)(.*)$") == "h")
