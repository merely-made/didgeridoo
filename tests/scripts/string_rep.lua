assert(string.rep("ab", 3) == "ababab")
assert(string.rep("ab", 1) == "ab")
assert(string.rep("ab", 0) == "")
assert(string.rep("ab", -1) == "")
assert(string.rep("", 100) == "")
assert(string.rep("x", 5, ",") == "x,x,x,x,x")
assert(string.rep("x", 1, ",") == "x")
assert(string.rep("x", 0, ",") == "")
assert(string.rep("", 3, "-") == "--")
assert(string.rep("ab", 2, "") == "abab")
assert(("ab"):rep(2) == "abab")
assert(#string.rep("a", 100000) == 100000)
assert(#string.rep("abc", 1000, "--") == 3 * 1000 + 2 * 999)
assert(string.rep(12, 2) == "1212")
assert(string.rep("a", 2.0) == "aa")

-- too large a result is an error, not an allocation
assert(not pcall(string.rep, "x", 1 << 40))
assert(not pcall(string.rep, "xx", math.maxinteger))
assert(not pcall(string.rep, "x", 1 << 30, "yy"))
assert(not pcall(string.rep))
assert(not pcall(string.rep, "x"))
assert(not pcall(string.rep, "x", "y"))
