local fmt = string.format

-- literals and %%
assert(fmt("") == "")
assert(fmt("abc") == "abc")
assert(fmt("100%%") == "100%")
assert(fmt("%%%%") == "%%")
assert(fmt("a%%b%dc", 5) == "a%b5c")

-- %d %i
assert(fmt("%d", 42) == "42")
assert(fmt("%d", -42) == "-42")
assert(fmt("%i", 7) == "7")
assert(fmt("%d", 0) == "0")
assert(fmt("%d", math.maxinteger) == "9223372036854775807")
assert(fmt("%d", math.mininteger) == "-9223372036854775808")
assert(fmt("%d", 3.0) == "3")
assert(fmt("%d", "10") == "10")
assert(fmt("%5d", 42) == "   42")
assert(fmt("%-5d|", 42) == "42   |")
assert(fmt("%05d", 42) == "00042")
assert(fmt("%05d", -42) == "-0042")
assert(fmt("%+d", 42) == "+42")
assert(fmt("%+d", -42) == "-42")
assert(fmt("% d", 42) == " 42")
assert(fmt("% d", -42) == "-42")
assert(fmt("%.3d", 7) == "007")
assert(fmt("%.0d", 0) == "")
assert(fmt("%5.3d", 7) == "  007")
assert(fmt("%-5.3d|", 7) == "007  |")
assert(fmt("%05.3d", 7) == "  007")
assert(fmt("%+05d", 42) == "+0042")
assert(fmt("%-+5d|", 42) == "+42  |")

-- %d rejects non-integral numbers and non-numbers
assert(not pcall(fmt, "%d", 3.5))
assert(not pcall(fmt, "%d", "3.5"))
assert(not pcall(fmt, "%d", "x"))
assert(not pcall(fmt, "%d", nil))
assert(not pcall(fmt, "%d", {}))
assert(not pcall(fmt, "%d", 1e100))
assert(not pcall(fmt, "%d", 0/0))
assert(not pcall(fmt, "%d"))
local ok, msg = pcall(fmt, "%d", 3.5)
assert(msg == "bad argument #2 to 'format' (number has no integer representation)")

-- %u
assert(fmt("%u", 42) == "42")
assert(fmt("%u", -1) == "18446744073709551615")
assert(fmt("%5u", 42) == "   42")
assert(fmt("%-5u|", 42) == "42   |")
assert(fmt("%05u", 42) == "00042")

-- %c
assert(fmt("%c", 65) == "A")
assert(fmt("%c%c%c", 76, 117, 97) == "Lua")
assert(fmt("%3c", 65) == "  A")
assert(fmt("%-3c|", 65) == "A  |")
assert(#fmt("%c", 0) == 1)
assert(fmt("%c", 256 + 65) == "A")

-- %x %X %o
assert(fmt("%x", 255) == "ff")
assert(fmt("%X", 255) == "FF")
assert(fmt("%o", 8) == "10")
assert(fmt("%#x", 255) == "0xff")
assert(fmt("%#X", 255) == "0XFF")
assert(fmt("%#x", 0) == "0")
assert(fmt("%#o", 8) == "010")
assert(fmt("%#o", 0) == "0")
assert(fmt("%x", -1) == "ffffffffffffffff")
assert(fmt("%08x", 255) == "000000ff")
assert(fmt("%#08x", 255) == "0x0000ff")
assert(fmt("%-8x|", 255) == "ff      |")
assert(fmt("%8x", 255) == "      ff")
assert(fmt("%.4x", 255) == "00ff")
assert(fmt("%x", 0) == "0")
assert(fmt("%.0x", 0) == "")

-- %f
assert(fmt("%f", 1.5) == "1.500000")
assert(fmt("%.2f", 3.14159) == "3.14")
assert(fmt("%.0f", 2.5) == "2")
assert(fmt("%.0f", 3.5) == "4")
assert(fmt("%.0f", 0.4) == "0")
assert(fmt("%#.0f", 3.0) == "3.")
assert(fmt("%f", -0.0) == "-0.000000")
assert(fmt("%8.2f", 3.14159) == "    3.14")
assert(fmt("%-8.2f|", 3.14159) == "3.14    |")
assert(fmt("%08.2f", 3.14159) == "00003.14")
assert(fmt("%08.2f", -3.14159) == "-0003.14")
assert(fmt("%+.1f", 2.0) == "+2.0")
assert(fmt("% .1f", 2.0) == " 2.0")
assert(fmt("%.3f", 1) == "1.000")
assert(fmt("%f", "2.5") == "2.500000")
assert(fmt("%.10f", 0.1) == "0.1000000000")
assert(fmt("%.20f", 0.1) == "0.10000000000000000555")
assert(fmt("%f", 1e15) == "1000000000000000.000000")
assert(fmt("%F", 1.5) == "1.500000")

-- %e %E
assert(fmt("%e", 12345.6789) == "1.234568e+04")
assert(fmt("%E", 12345.6789) == "1.234568E+04")
assert(fmt("%.2e", 12345.6789) == "1.23e+04")
assert(fmt("%.0e", 12345.6789) == "1e+04")
assert(fmt("%#.0e", 12345.6789) == "1.e+04")
assert(fmt("%e", 0) == "0.000000e+00")
assert(fmt("%e", 1e-5) == "1.000000e-05")
assert(fmt("%e", 1e100) == "1.000000e+100")
assert(fmt("%e", -1.5) == "-1.500000e+00")
assert(fmt("%12.3e|", 1234.5) == "   1.234e+03|")
assert(fmt("%-14.2e|", 1234.5) == "1.23e+03      |")
assert(fmt("%014.2e", 1234.5) == "0000001.23e+03")

-- %g %G
assert(fmt("%g", 100000) == "100000")
assert(fmt("%g", 1000000) == "1e+06")
assert(fmt("%g", 0.0001) == "0.0001")
assert(fmt("%g", 0.00001) == "1e-05")
assert(fmt("%g", 1.5) == "1.5")
assert(fmt("%g", 0) == "0")
assert(fmt("%g", 1e100) == "1e+100")
assert(fmt("%G", 1e-10) == "1E-10")
assert(fmt("%.3g", 1234.5678) == "1.23e+03")
assert(fmt("%.10g", 1234.5678) == "1234.5678")
assert(fmt("%.3g", 0.00012345) == "0.000123")
assert(fmt("%#g", 1.5) == "1.50000")
assert(fmt("%#.3g", 1) == "1.00")
assert(fmt("%.0g", 15) == "2e+01")
assert(fmt("%g", 123456789) == "1.23457e+08")
assert(fmt("%10g|", 1.5) == "       1.5|")
assert(fmt("%-10g|", 1.5) == "1.5       |")
assert(fmt("%+g", 1.5) == "+1.5")
assert(fmt("%.14g", 0.1) == "0.1")
assert(fmt("%.17g", 0.1) == "0.10000000000000001")
assert(fmt("%.14g", 2^53) == "9.007199254741e+15")
assert(fmt("%g", -0.0) == "-0")

-- inf and nan
local inf = math.huge
assert(fmt("%f", inf) == "inf")
assert(fmt("%f", -inf) == "-inf")
assert(fmt("%e", inf) == "inf")
assert(fmt("%g", inf) == "inf")
assert(fmt("%F", inf) == "INF")
assert(fmt("%E", -inf) == "-INF")
assert(fmt("%G", inf) == "INF")
assert(fmt("%5.1f|", inf) == "  inf|")
assert(fmt("%05.1f|", inf) == "  inf|")
assert(fmt("%-5.1f|", inf) == "inf  |")
assert(fmt("%+f", inf) == "+inf")
assert(fmt("%f", 0/0) == "nan" or fmt("%f", 0/0) == "-nan")

-- %a (hex floats)
assert(fmt("%a", 1) == "0x1p+0")
assert(fmt("%a", 0.5) == "0x1p-1")
assert(fmt("%a", 255.5) == "0x1.ffp+7")
assert(fmt("%a", 0) == "0x0p+0")
assert(fmt("%a", -2) == "-0x1p+1")
assert(fmt("%A", 255.5) == "0X1.FFP+7")
assert(fmt("%a", 0.1) == "0x1.999999999999ap-4")
assert(fmt("%.2a", 1) == "0x1.00p+0")
assert(fmt("%.1a", 1.5) == "0x1.8p+0")
assert(fmt("%.0a", 1.5) == "0x2p+0")
assert(fmt("%.0a", 2.5) == "0x1p+1")
assert(fmt("%a", inf) == "inf")
assert(fmt("%a", 2^-1074) == "0x0.0000000000001p-1022")
assert(fmt("%+a", 1) == "+0x1p+0")

-- %s
assert(fmt("%s", "hello") == "hello")
assert(fmt("%s", "") == "")
assert(fmt("%s", 42) == "42")
assert(fmt("%s", true) == "true")
assert(fmt("%s", false) == "false")
assert(fmt("%s", nil) == "nil")
assert(fmt("%s|%s", "a", "b") == "a|b")
assert(fmt("%10s|", "abc") == "       abc|")
assert(fmt("%-10s|", "abc") == "abc       |")
assert(fmt("%.2s", "abcdef") == "ab")
assert(fmt("%.0s", "abcdef") == "")
assert(fmt("%5.2s|", "abcdef") == "   ab|")
assert(fmt("%.10s", "abc") == "abc")
assert(fmt("%s", "a\0b") == "a\0b")
assert(#fmt("%s", "a\0b") == 3)
assert(not pcall(fmt, "%5s", "a\0b"))
assert(not pcall(fmt, "%.1s", "a\0b"))
assert(#fmt("%s", string.rep("x", 500)) == 500)
assert(#fmt("%10s", string.rep("x", 500)) == 500)
assert(fmt("%s", fmt) == tostring(fmt))
local tbl = {}
assert(fmt("%s", tbl) == tostring(tbl))

-- %s uses __tostring
local obj = setmetatable({}, { __tostring = function() return "OBJ" end })
assert(fmt("%s", obj) == "OBJ")
assert(fmt("[%s]", obj) == "[OBJ]")
assert(fmt("%5s|", obj) == "  OBJ|")
assert(fmt("%s %s %s", obj, "x", obj) == "OBJ x OBJ")
assert(fmt("%d %s", 7, obj) == "7 OBJ")
assert(fmt("%.2s", obj) == "OB")
local bad = setmetatable({}, { __tostring = function() return {} end })
assert(not pcall(fmt, "%s", bad))
local boom = setmetatable({}, { __tostring = function() error("boom") end })
assert(not pcall(fmt, "%s", boom))
-- __tostring may itself format
local nested = setmetatable({}, { __tostring = function(self) return fmt("<%d>", 9) end })
assert(fmt("%s", nested) == "<9>")

-- %q
assert(fmt("%q", "hello") == '"hello"')
assert(fmt("%q", 'say "hi"') == '"say \\"hi\\""')
assert(fmt("%q", "a\\b") == '"a\\\\b"')
assert(fmt("%q", "a\nb") == '"a\\\nb"')
assert(fmt("%q", "a\0b") == '"a\\0b"')
assert(fmt("%q", "a\0001") == '"a\\0001"')
assert(fmt("%q", "\r") == '"\\13"')
assert(fmt("%q", "\0019") == '"\\0019"')
assert(fmt("%q", "tab\there") == '"tab\\9here"')
assert(fmt("%q", "") == '""')
assert(fmt("%q", 42) == "42")
assert(fmt("%q", -7) == "-7")
assert(fmt("%q", math.mininteger) == "0x8000000000000000")
assert(fmt("%q", math.maxinteger) == "9223372036854775807")
assert(fmt("%q", nil) == "nil")
assert(fmt("%q", true) == "true")
assert(fmt("%q", false) == "false")
assert(fmt("%q", 0.5) == "0x1p-1")
assert(fmt("%q", inf) == "1e9999")
assert(fmt("%q", -inf) == "-1e9999")
assert(fmt("%q", 0/0) == "(0/0)")
assert(not pcall(fmt, "%q", {}))
assert(not pcall(fmt, "%q", print))
assert(not pcall(fmt, "%10q", "x"))
assert(not pcall(fmt, "%.3q", "x"))
assert(not pcall(fmt, "%-q", "x"))

-- several conversions in one format
assert(fmt("%d-%s-%5.1f", 1, "two", 3.0) == "1-two-  3.0")
assert(fmt("%s=%d", "x", 10) == "x=10")
assert(fmt("%3d|%-3d|%03d", 1, 2, 3) == "  1|2  |003")
assert(fmt("%s", fmt("%d", 5)) == "5")
assert(("%d items"):format(3) == "3 items")
assert(("%s"):rep(2):format("a", "b") == "ab")

-- extra arguments are ignored; missing ones are errors
assert(fmt("%d", 1, 2, 3) == "1")
assert(fmt("none", 1, 2) == "none")
assert(not pcall(fmt, "%d %d", 1))
assert(not pcall(fmt, "%s"))
assert(not pcall(fmt))

-- invalid conversions
assert(not pcall(fmt, "%"))
assert(not pcall(fmt, "%y", 1))
assert(not pcall(fmt, "%z", 1))
assert(not pcall(fmt, "%5", 1))
assert(not pcall(fmt, "%.", 1))
assert(not pcall(fmt, "%123d", 1))
assert(not pcall(fmt, "%.123f", 1))
assert(not pcall(fmt, "%#d", 1))
assert(not pcall(fmt, "%0s", "x"))
assert(not pcall(fmt, "%+s", "x"))
assert(not pcall(fmt, "%.3c", 65))
assert(not pcall(fmt, "%#c", 65))
assert(not pcall(fmt, "%+x", 1))
local ok, msg = pcall(fmt, "%y", 1)
assert(msg == "invalid conversion '%y' to 'format'")

-- width and precision up to two digits are fine
assert(#fmt("%99d", 1) == 99)
assert(fmt("%.99f", 1):sub(1, 4) == "1.00")
assert(#fmt("%.99f", 1) == 101)
